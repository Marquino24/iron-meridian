// Copies the game simulation (js/) and the era maps into the tick Edge
// Function (supabase/functions/tick/game/, gitignored), ready to deploy:
//   node tools/build-functions.mjs && supabase functions deploy tick --no-verify-jwt
import { cpSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { gzipSync } from 'node:zlib';

const root = new URL('../', import.meta.url);
const out = new URL('supabase/functions/tick/game/', root);
rmSync(out, { recursive: true, force: true });
mkdirSync(new URL('js/', out), { recursive: true });
mkdirSync(new URL('data/', out), { recursive: true });
let files = 0;
for (const f of readdirSync(new URL('js/', root))) if (f.endsWith('.js')) { cpSync(new URL(`js/${f}`, root), new URL(`js/${f}`, out)); files++; }
// The era maps travel inside the function's bundle as one module of gzip'd
// base64 (a deployed function only contains what its code imports, and the
// server-side bundle is capped at 5 MB: the raw JSON alone is 4.6 MB).
const eras = {};
for (const f of readdirSync(new URL('data/eras/', root))) {
  if (!f.endsWith('.json')) continue;
  eras[f.replace('.json', '')] = gzipSync(readFileSync(new URL(`data/eras/${f}`, root)), { level: 9 }).toString('base64');
  files++;
}
writeFileSync(new URL('data/eras.js', out), `// GENERATED by tools/build-functions.mjs: era maps, gzip'd JSON in base64.\nexport const ERAS = ${JSON.stringify(eras)};\n`);
const kb = Math.round(Object.values(eras).reduce((t, v) => t + v.length, 0) / 1024);
console.log(`copied ${files} files into ${out.pathname} (era maps ${kb} KB as gzip base64)`);
