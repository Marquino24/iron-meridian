// Writes docs/TECH.md: every era's tech tree (names, effects, requirements, costs).
//   node tools/print-tech.mjs
import { writeFileSync } from 'node:fs';
import { techTree, BRANCHES, TOTAL_HOURS, legacyMap } from '../js/tech.js';
import { ERAS } from '../js/eras.js';
import { resourceSet } from '../js/resources.js';
import { describeEffects } from '../js/research.js';
import { rosterFor } from '../js/units.js';
import { buildingName } from '../js/buildings.js';
import { TECH_TASTE } from '../js/ai.js';

const ROMAN = ['', 'I', 'II', 'III', 'IV'];
const out = [
  '# Tech trees',
  '',
  'Generated by `node tools/print-tech.mjs` from `js/tech.js`.',
  '',
  'Every era has its own tree: three branches (Military, Economy, Infrastructure), 29–31 techs, its own shape (which branch runs to a tier IV capstone) and 3–5 **signature techs** (★) whose effects exist only in that era. The Fictional World borrows one signature from each age.',
  '',
  `- **Time:** each tree adds up to ${TOTAL_HOURS.toLocaleString('en')} game hours of research. A medium nation that keeps its slots busy finishes in about 2.3–2.5 real hours at 1× (\`node tools/check-war.mjs\`, section 3c).`,
  '- **Slots:** one research slot to start. The tier I Economy tech that gives "+1 research slot" opens a second, and the tier III one a third. Up to 5 more techs can wait in the queue.',
  '- **Cost:** grows by tier and is scaled so every tree costs about the same in total. Only the era\'s resources apply.',
  '- **Computer nations:** they research lower tiers first, in their personality\'s branch order. Each tech is tagged attack, defend, grow or hold, and each personality weighs those tags: ' +
    Object.entries(TECH_TASTE).filter(([k]) => k !== 'conqueror').map(([k, w]) => `${k} ${Object.entries(w).sort((a, b) => b[1] - a[1]).map(([t, v]) => `${t} ×${v}`).join(', ')}`).join('; ') + '. Signature techs count the weight extra, so aggressive nations reach siege engines and blitzkrieg early, and defensive ones reach castles, radar and the deterrent early.',
  '- **Old saves:** saves from before step 10 used one shared 28-tech tree (ids m1–i9). On loading, each researched tech becomes the new tech with the same main effect, together with that tech\'s requirements. A tech with no match is refunded at its old cost, research that was in progress is refunded, and the old queue is cleared. The player is told in the event feed.',
  '',
  '## Signature techs at a glance',
  '',
  '| Era | Signature techs |',
  '|---|---|',
];
const body = [];
for (const era of ERAS) {
  const rs = resourceSet(era.id);
  const tree = techTree(era.id, rs.keys);
  const byId = Object.fromEntries(tree.map((t) => [t.id, t]));
  const ctx = { roster: rosterFor(era.id), buildingName: (k) => buildingName(era.id, k), label: (k) => rs.labels[k] ?? k };
  out.push(`| ${era.label} | ${tree.filter((t) => t.signature).map((t) => `**${t.name}** (${BRANCHES.find((b) => b.id === t.branch).label} ${ROMAN[t.tier]}): ${describeEffects(t.effects, ctx).map((d) => d.replace('★ ', '')).join('; ')}`).join('<br>')} |`);
  const shape = BRANCHES.map((b) => { const ts = tree.filter((t) => t.branch === b.id); return `${b.label} ${ts.length} techs to tier ${ROMAN[Math.max(...ts.map((t) => t.tier))]}`; }).join(', ');
  const tiers = [1, 2, 3, 4].map((tier) => tree.find((t) => t.tier === tier)).filter(Boolean)
    .map((t) => `tier ${ROMAN[t.tier]}: ${Object.entries(t.cost).map(([k, v]) => `${v} ${rs.labels[k] ?? k}`).join(', ')}, ${t.hours} h (${(t.hours / 60).toFixed(0)} min at 1×)`).join('; ');
  const lm = legacyMap(era.id, tree);
  const refunds = Object.entries(lm).filter(([, v]) => !v).map(([k]) => k);
  body.push(`## ${era.label} (${era.year})`, '', `${tree.length} techs: ${shape}.`, '', `Cost and time per tier: ${tiers}.`, '',
    `Old saves: ${Object.values(lm).filter(Boolean).length} of 28 old techs carry over${refunds.length ? `; refunded: ${refunds.join(', ')}` : ''}.`, '',
    '| Branch | Tier | Tech | Effects | Requires | AI tag |', '|---|---|---|---|---|---|');
  for (const b of BRANCHES) {
    for (const t of tree.filter((x) => x.branch === b.id).sort((x, y) => x.tier - y.tier)) {
      body.push(`| ${b.label} | ${ROMAN[t.tier]} | ${t.signature ? `★ **${t.name}**` : t.name} | ${describeEffects(t.effects, ctx).join('; ')} | ${t.req.map((q) => byId[q].name).join(', ') || '—'} | ${t.ai} |`);
    }
  }
  body.push('');
}
out.push('', ...body);
writeFileSync(new URL('../docs/TECH.md', import.meta.url), out.join('\n'));
console.log(`wrote docs/TECH.md (${ERAS.length} eras)`);
