// Writes docs/TECH.md: every era's tech tree (names, effects, requirements, costs).
//   node tools/print-tech.mjs
import { writeFileSync } from 'node:fs';
import { techTree, BRANCHES } from '../js/tech.js';
import { ERAS } from '../js/eras.js';
import { resourceSet } from '../js/resources.js';
import { describeEffects } from '../js/research.js';
import { rosterFor } from '../js/units.js';
import { buildingName } from '../js/buildings.js';

const ROMAN = ['', 'I', 'II', 'III'];
const out = ['# Tech trees', '', 'Generated by `node tools/print-tech.mjs` from `js/tech.js`. Every era uses the same 28-tech skeleton (same effects and requirements), with era names. One research slot to start; the tier II Economy tech that gives "+1 research slot" opens a second.', ''];
const set = resourceSet('ww2');
const t0 = techTree('ww2', set.keys);
out.push('Cost and time per tier (only the era\'s resources apply): ' + [1, 2, 3].map((tier) => {
  const t = t0.find((x) => x.tier === tier);
  return `tier ${ROMAN[tier]}: ${Object.entries(t.cost).map(([k, v]) => `${v} ${k}`).join(', ')}${tier > 1 ? ' (+ electronics from the Cold War on)' : ''}, ${t.hours / 24} days`;
}).join('; ') + '.', '');
for (const era of ERAS) {
  const rs = resourceSet(era.id);
  const tree = techTree(era.id, rs.keys);
  const byId = Object.fromEntries(tree.map((t) => [t.id, t]));
  out.push(`## ${era.label} (${era.year})`, '', '| Branch | Tier | Tech | Effects | Requires |', '|---|---|---|---|---|');
  for (const b of BRANCHES) {
    for (const t of tree.filter((x) => x.branch === b.id)) {
      const fx = describeEffects(t.effects, { roster: rosterFor(era.id), buildingName: (k) => buildingName(era.id, k), label: (k) => rs.labels[k] ?? k });
      out.push(`| ${b.label} | ${ROMAN[t.tier]} | ${t.name} | ${fx.join('; ')} | ${t.req.map((q) => byId[q].name).join(', ') || '—'} |`);
    }
  }
  out.push('');
}
writeFileSync(new URL('../docs/TECH.md', import.meta.url), out.join('\n'));
console.log(`wrote docs/TECH.md (${ERAS.length} eras)`);
